export function getElaPassageBankTeksCluster(teksStandard) {
  if (typeof teksStandard !== "string") {
    return null;
  }

  return ELA_PASSAGE_BANK_TEKS_CLUSTERS[teksStandard.trim()] ?? null;
}

export function isAllowedElaPackageQuestionTeks({ primaryTeks, questionTeks }) {
  const cluster = getElaPassageBankTeksCluster(primaryTeks);

  if (!cluster || typeof questionTeks !== "string") {
    return false;
  }

  return [cluster.primary_teks, ...cluster.supported_teks].includes(
    questionTeks.trim(),
  );
}

export function buildElaQuestionTeksPlan({ primaryTeks, totalQuestions }) {
  const cluster = getElaPassageBankTeksCluster(primaryTeks);

  if (!cluster) {
    throw new Error(
      `No ELA passage-bank TEKS cluster configured for ${primaryTeks}.`,
    );
  }

  const total = Number(totalQuestions);

  if (!Number.isInteger(total) || total < 1) {
    throw new Error("totalQuestions must be a positive integer.");
  }

  const supported = cluster.supported_teks;

  // Keep very small test packages primary-only.
  if (total < 5 || supported.length === 0) {
    return [
      {
        teks_standard: cluster.primary_teks,
        count: total,
      },
    ];
  }

  const primaryCount = Math.ceil(total * 0.6);
  let remaining = total - primaryCount;

  const plan = [
    {
      teks_standard: cluster.primary_teks,
      count: primaryCount,
    },
  ];

  for (const teksStandard of supported) {
    if (remaining <= 0) break;

    plan.push({
      teks_standard: teksStandard,
      count: 1,
    });

    remaining -= 1;
  }

  // Give leftover questions back to the primary TEKS.
  if (remaining > 0) {
    plan[0].count += remaining;
  }

  return plan;
}
