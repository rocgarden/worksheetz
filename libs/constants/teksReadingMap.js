// ── Flat list builder for dropdown ────────────────────────────────────────────
export function buildTeksAllowed(gradeLevel) {
  const key = `grade${gradeLevel}`;
  const m = TEKS_READING_MAP[key];
  if (!m) return [];
  const allTeks = Object.values(m).flat();
  return [...new Set(allTeks.filter(Boolean))];
}

